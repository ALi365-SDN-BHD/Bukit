using Bukit.Config;
using Bukit.Shared;

namespace Bukit.Engine;

/// <summary>Fails before copying a default language static file that would occupy a root-owned output.</summary>
internal static class I18nRootOutputConflictGuard
{
    internal static void Validate(AppConfig config, string? staticDir, string? parentStaticDir)
    {
        if (!I18nOutputLayout.IsRootLanguageVariant(config))
        {
            return;
        }

        var conflicts = RootOwnedOutputs(config);
        foreach (var directory in new[] { parentStaticDir, staticDir })
        {
            if (string.IsNullOrWhiteSpace(directory) || !Directory.Exists(directory))
            {
                continue;
            }

            foreach (var file in Directory.EnumerateFiles(directory, "*", SearchOption.AllDirectories))
            {
                var relative = BuildPathUtils.NormalizeRelPath(Path.GetRelativePath(directory, file));
                if (conflicts.TryGetValue(relative, out var setting))
                {
                    throw new BukitException(
                        $"Default language static file '{file}' conflicts with root output '{relative}' generated by {setting}.",
                        DiagnosticCode.I18nRootOutputConflict);
                }
            }
        }
    }

    private static Dictionary<string, string> RootOwnedOutputs(AppConfig config)
    {
        var site = config.Site;
        var outputs = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            ["agent-manifest.json"] = "the agent manifest writer"
        };
        if (site.Seo.Geo.Enabled && site.Seo.Geo.LlmsTxt)
        {
            outputs["llms.txt"] = "site.seo.geo.llmsTxt";
        }

        if (site.Seo.Geo.Enabled && site.Seo.Geo.LlmsFullTxt)
        {
            outputs["llms-full.txt"] = "site.seo.geo.llmsFullTxt";
        }

        var sitemapMode = (site.SitemapMode ?? "split").Trim().ToLowerInvariant();
        if (sitemapMode is "merged" or "index")
        {
            outputs["sitemap.xml"] = $"site.sitemapMode: {sitemapMode}";
        }

        if (!string.IsNullOrWhiteSpace(site.Url) && SiteModeResolver.ResolveFeedMode(site) == "merged")
        {
            var formats = site.Feed.Formats.Select(format => format.Trim().ToLowerInvariant()).ToHashSet(StringComparer.Ordinal);
            if (formats.Count == 0 || formats.Contains("rss")) outputs["rss.xml"] = "site.feed.mode: merged";
            if (formats.Contains("atom")) outputs[BuildPathUtils.NormalizeRelPath(Path.Combine(site.Feed.Path, "atom.xml"))] = "site.feed.mode: merged";
            if (formats.Contains("json")) outputs[BuildPathUtils.NormalizeRelPath(Path.Combine(site.Feed.Path, "feed.json"))] = "site.feed.mode: merged";
        }

        outputs.Remove("robots.txt");
        return outputs;
    }
}
