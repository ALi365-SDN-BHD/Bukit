using Bukit.Config;
using Bukit.Shared;

namespace Bukit.Engine;

/// <summary>Fails before copying a default language static file that would occupy a root-owned output.</summary>
internal static class I18nRootOutputConflictGuard
{
    internal static void Validate(AppConfig config, string? staticDir, string? parentStaticDir)
    {
        if (!I18nOutputLayout.IsRootLanguageVariant(config))
        {
            return;
        }

        // The root projection plan is the single list of what root writers generate.
        var rootOutputs = PublicOutputLifecycle.ProjectionPlan(config, [], root: true);
        var listings = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
        var options = I18nOutputLayout.StaticCopyOptions(config.Build);
        foreach (var output in rootOutputs)
        {
            foreach (var directory in new[] { parentStaticDir, staticDir })
            {
                var file = FindIgnoringCase(directory, output.Destination, listings, options);
                if (file is not null && !IsStaticRobotsOverride(output.Destination, file))
                {
                    throw new BukitException(
                        $"Default language static file '{file}' conflicts with root output '{output.Destination}' generated by {Setting(config.Site, output.Source)}.",
                        DiagnosticCode.I18nRootOutputConflict);
                }
            }
        }
    }

    /// <summary>
    /// A default language static <c>robots.txt</c> replaces the generated one, but only under that
    /// exact name: crawlers request only the lowercase path, so <c>Robots.txt</c> would leave the
    /// site without robots rules on a case-sensitive host.
    /// </summary>
    private static bool IsStaticRobotsOverride(string destination, string file)
        => string.Equals(destination, "robots.txt", StringComparison.Ordinal) &&
            string.Equals(Path.GetFileName(file), "robots.txt", StringComparison.Ordinal);

    /// <summary>
    /// Case-insensitive lookup on every platform, so Linux and macOS report the same conflicts.
    /// '.' segments and backslashes are normalized as the writers resolve them; dot-prefixed
    /// segments and symlinks the copy step skips do not count; each directory is listed at most
    /// once per validation.
    /// </summary>
    private static string? FindIgnoringCase(
        string? root,
        string relativePath,
        Dictionary<string, Dictionary<string, string>> listings,
        DirectoryCopyOptions options)
    {
        if (string.IsNullOrWhiteSpace(root) || !Directory.Exists(root))
        {
            return null;
        }

        var segments = relativePath.Split(['/', '\\'], StringSplitOptions.RemoveEmptyEntries)
            .Where(segment => segment != ".")
            .ToArray();
        if (segments.Length == 0 || segments.Contains(".."))
        {
            return null;
        }

        var current = root;
        foreach (var segment in segments)
        {
            if (DirectoryCopy.ShouldSkipDotfile(segment, options))
            {
                return null;
            }

            if (!listings.TryGetValue(current, out var entries))
            {
                if (!Directory.Exists(current))
                {
                    return null;
                }

                entries = Directory.EnumerateFileSystemEntries(current)
                    .Where(path => !DirectoryCopy.IsSymlink(path) ||
                        options.FollowSymlinks && DirectoryCopy.IsSafeStaticLink(path, root, options))
                    .GroupBy(Path.GetFileName, StringComparer.OrdinalIgnoreCase)
                    .ToDictionary(
                        group => group.Key!,
                        // Names differing only in case (case-sensitive filesystems): pick one by
                        // ordinal order so the reported conflict does not depend on listing order.
                        group => group.Order(StringComparer.Ordinal).First(),
                        StringComparer.OrdinalIgnoreCase);
                listings[current] = entries;
            }

            if (!entries.TryGetValue(segment, out var match))
            {
                return null;
            }

            current = match;
        }

        return File.Exists(current) ? current : null;
    }

    private static string Setting(SiteConfig site, string kind) => kind switch
    {
        "agent-manifest" => "the agent manifest writer",
        "llms" => "site.seo.geo.llmsTxt",
        "llms-full" => "site.seo.geo.llmsFullTxt",
        "sitemap" => $"site.sitemapMode: {(site.SitemapMode ?? "split").Trim().ToLowerInvariant()}",
        "feed" or "atom" or "jsonfeed" => "site.feed.mode: merged",
        "search" => $"site.search.mode: {SiteModeResolver.ResolveSearchMode(site)}",
        _ => kind
    };
}
