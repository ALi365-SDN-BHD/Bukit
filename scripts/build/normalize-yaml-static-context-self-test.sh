#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
normalizer="$script_dir/normalize-yaml-static-context.py"
tmp_dir="$(mktemp -d "${TMPDIR:-/tmp}/bukit-yaml-normalizer.XXXXXX")"
trap 'rm -rf "$tmp_dir"' EXIT

write_fixture() {
  local output="$1"
  local first_guid="$2"
  local second_guid="$3"

  cat >"$output" <<EOF
﻿namespace Bukit.Theme;
internal sealed class Fixture
{
    private readonly object accessor_${first_guid} = new();
    private readonly object other_${second_guid} = new();
    public object Get() => accessor_${first_guid};
}
EOF
}

write_fixture "$tmp_dir/first.g.cs" \
  "11111111111111111111111111111111" \
  "22222222222222222222222222222222"
write_fixture "$tmp_dir/second.g.cs" \
  "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa" \
  "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"

python3 "$normalizer" "$tmp_dir/first.g.cs" "$tmp_dir/first.normalized.cs"
python3 "$normalizer" "$tmp_dir/second.g.cs" "$tmp_dir/second.normalized.cs"

cmp "$tmp_dir/first.normalized.cs" "$tmp_dir/second.normalized.cs"
grep -Fq '// Generated by Vecc.YamlDotNet.Analyzers.StaticGenerator and normalized by scripts/build/normalize-yaml-static-context.py.' \
  "$tmp_dir/first.normalized.cs"
grep -Fq 'accessor_4fc565ab79d6764db998ad5eba4dd7d6' "$tmp_dir/first.normalized.cs"
grep -Fq 'other_d9298a10d1b0735837dc4bd85dac641b' "$tmp_dir/first.normalized.cs"
if grep -Eq '[A-Za-z_][A-Za-z0-9_]*_(11111111111111111111111111111111|22222222222222222222222222222222)' \
  "$tmp_dir/first.normalized.cs"; then
  echo "normalize-yaml-static-context self-test: random suffix remained" >&2
  exit 1
fi

cat >"$tmp_dir/no-match.g.cs" <<'EOF'
namespace Bukit.Theme;
internal sealed class NoGeneratedIdentifiers;
EOF
if python3 "$normalizer" "$tmp_dir/no-match.g.cs" "$tmp_dir/no-match.normalized.cs"; then
  echo "normalize-yaml-static-context self-test: input without generated identifiers succeeded" >&2
  exit 1
fi
if [[ -e "$tmp_dir/no-match.normalized.cs" ]]; then
  echo "normalize-yaml-static-context self-test: failed normalization left an output file" >&2
  exit 1
fi

cat >"$tmp_dir/ambiguous.g.cs" <<'EOF'
namespace Bukit.Theme;
internal sealed class Ambiguous
{
    private object accessor_11111111111111111111111111111111 = new();
    private object accessor_22222222222222222222222222222222 = new();
}
EOF
if python3 "$normalizer" "$tmp_dir/ambiguous.g.cs" "$tmp_dir/ambiguous.normalized.cs"; then
  echo "normalize-yaml-static-context self-test: ambiguous base-to-GUID mapping succeeded" >&2
  exit 1
fi
if [[ -e "$tmp_dir/ambiguous.normalized.cs" ]]; then
  echo "normalize-yaml-static-context self-test: ambiguous input left an output file" >&2
  exit 1
fi

echo "normalize-yaml-static-context self-test: PASS"
