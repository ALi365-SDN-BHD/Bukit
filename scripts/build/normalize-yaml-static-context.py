#!/usr/bin/env python3
"""Normalize random YamlDotNet static-generator identifier suffixes."""

from __future__ import annotations

import hashlib
import os
from pathlib import Path
import re
import sys
import tempfile
import xml.etree.ElementTree as ET


IDENTIFIER_PATTERN = re.compile(
    r"(?<![A-Za-z0-9_])"
    r"(?P<base>[A-Za-z_][A-Za-z0-9_]*)_"
    r"(?P<guid>[0-9a-f]{32})"
    r"(?![A-Za-z0-9_])"
)
ACCESSOR_DEFINITION_PATTERN = re.compile(
    r"\bclass\s+"
    r"(?P<identifier>(?P<base>[A-Za-z_][A-Za-z0-9_]*)_(?P<guid>[0-9a-f]{32}))"
    r"\s*:\s*YamlDotNet\.Serialization\.IObjectAccessor\b"
)
GENERATOR_PACKAGE = "Vecc.YamlDotNet.Analyzers.StaticGenerator"
PACKAGE_PROPS_PATH = Path(__file__).resolve().parents[2] / "Directory.Packages.props"


class NormalizationError(ValueError):
    """Raised when generator output cannot be normalized safely."""


def read_generator_version(package_props_path: Path = PACKAGE_PROPS_PATH) -> str:
    try:
        root = ET.parse(package_props_path).getroot()
    except (OSError, ET.ParseError) as error:
        raise NormalizationError(
            f"cannot read central package versions from {package_props_path}: {error}"
        ) from error

    versions = [
        element.attrib.get("Version", "").strip()
        for element in root.iter()
        if element.tag.rsplit("}", 1)[-1] == "PackageVersion"
        and element.attrib.get("Include") == GENERATOR_PACKAGE
    ]
    if len(versions) != 1 or not versions[0]:
        raise NormalizationError(
            f"expected exactly one non-empty central version for {GENERATOR_PACKAGE}, "
            f"found {len(versions)}"
        )
    return versions[0]


def provenance_header() -> str:
    return (
        "// <auto-generated>\n"
        "// Generated by Vecc.YamlDotNet.Analyzers.StaticGenerator and normalized by "
        "scripts/build/normalize-yaml-static-context.py.\n"
        f"// Generator package: {GENERATOR_PACKAGE} {read_generator_version()}.\n"
        "// Input: src/Bukit-Core/Bukit.Theme/ThemeManifestYamlStaticContext.cs.\n"
        "// Do not edit manually.\n"
        "// </auto-generated>\n"
    )


def stable_suffix(base: str) -> str:
    return hashlib.sha256(base.encode("utf-8")).hexdigest()[:32]


def normalize(source: str) -> str:
    header = provenance_header()
    source = source.replace("\r\n", "\n").replace("\r", "\n")
    source = source.removeprefix(header)
    if "\0" in source:
        raise NormalizationError("input contains a NUL character")

    definitions = list(ACCESSOR_DEFINITION_PATTERN.finditer(source))
    if not definitions:
        raise NormalizationError("input contains no generated IObjectAccessor definitions")

    source_guids: dict[str, set[str]] = {}
    identifiers: dict[str, str] = {}
    for match in definitions:
        source_guids.setdefault(match.group("base"), set()).add(match.group("guid"))
        identifiers[match.group("identifier")] = match.group("base")

    ambiguous_bases = sorted(base for base, guids in source_guids.items() if len(guids) != 1)
    if ambiguous_bases:
        raise NormalizationError(
            "generated identifier base maps to multiple GUID suffixes: "
            + ", ".join(ambiguous_bases)
        )

    suffix_owners: dict[str, str] = {}
    for base in sorted(source_guids):
        suffix = stable_suffix(base)
        existing_owner = suffix_owners.setdefault(suffix, base)
        if existing_owner != base:
            raise NormalizationError(
                f"deterministic suffix collision between {existing_owner!r} and {base!r}"
            )

    identifier_matches = list(IDENTIFIER_PATTERN.finditer(source))
    unknown_identifiers = sorted(
        {match.group(0) for match in identifier_matches if match.group(0) not in identifiers}
    )
    if unknown_identifiers:
        raise NormalizationError(
            "GUID-suffixed identifiers are not declared IObjectAccessor classes: "
            + ", ".join(unknown_identifiers)
        )

    def replace_identifier(match: re.Match[str]) -> str:
        base = identifiers[match.group(0)]
        return f"{base}_{stable_suffix(base)}"

    body = IDENTIFIER_PATTERN.sub(replace_identifier, source)
    identifiers_expected_to_change = {
        identifier
        for identifier, base in identifiers.items()
        if identifier != f"{base}_{stable_suffix(base)}"
    }
    remaining_identifiers = sorted(
        identifiers_expected_to_change.intersection(
            match.group(0) for match in IDENTIFIER_PATTERN.finditer(body)
        )
    )
    if remaining_identifiers:
        raise NormalizationError(
            "normalization left generated identifiers unchanged: "
            + ", ".join(str(identifier) for identifier in remaining_identifiers)
        )
    body = body.removeprefix("\ufeff")
    body = "\n".join(line.rstrip() for line in body.split("\n"))
    body = body.rstrip("\n") + "\n"
    return header + body


def write_atomic(output_path: Path, content: str) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{output_path.name}.",
        dir=output_path.parent,
    )
    temporary_path = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
        os.replace(temporary_path, output_path)
    except BaseException:
        temporary_path.unlink(missing_ok=True)
        raise


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(
            "usage: normalize-yaml-static-context.py INPUT OUTPUT",
            file=sys.stderr,
        )
        return 2

    input_path = Path(argv[1])
    output_path = Path(argv[2])
    try:
        raw_source = input_path.read_bytes().decode("utf-8-sig")
        normalized_source = normalize(raw_source)
        write_atomic(output_path, normalized_source)
    except (OSError, UnicodeError, NormalizationError) as error:
        print(f"normalize-yaml-static-context: {error}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
